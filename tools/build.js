// Content-hashed build: esbuild bundles src/main.js -> dist/game.<hash>.js with ESM code-splitting
// (Rapier lands in its own chunk), rewrites index.html to the entry, writes sw.js
// (own scope ./, cache prefix "ss-"), and skips work when inputs are unchanged (build cache in .buildcache).
const esbuild = require('esbuild'), fs = require('fs'), path = require('path'), crypto = require('crypto'), zlib = require('zlib');
const R = path.resolve(__dirname, '..'), P = f => path.join(R, f);
const walk = d => fs.existsSync(P(d)) ? fs.readdirSync(P(d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(d + '/' + e.name) : [d + '/' + e.name]) : [];
(async () => {
  const srcs = [...walk('src'), 'index.html', 'style.css', 'tools/build.js'].sort();
  const inHash = crypto.createHash('sha1'); srcs.forEach(f => inHash.update(f + fs.readFileSync(P(f))));
  const key = inHash.digest('hex'), cache = P('.buildcache');
  if (!process.argv.includes('--force') && fs.existsSync(cache) && fs.readFileSync(cache, 'utf8') === key && fs.existsSync(P('dist/index.html'))) { console.log('build: cached, inputs unchanged'); return; }
  fs.rmSync(P('dist'), { recursive: true, force: true }); fs.mkdirSync(P('dist'));
  const built = await esbuild.build({
    entryPoints: [P('src/main.js')],
    bundle: true,
    format: 'esm',
    splitting: true,
    minify: true,
    target: ['safari15'],
    outdir: P('dist'),
    entryNames: 'game.[hash]',
    chunkNames: 'chunk.[hash]',
    assetNames: 'asset.[hash]',
    legalComments: 'eof',
    metafile: true,
  });
  let entry = null;
  for (const [outfile, info] of Object.entries(built.metafile.outputs)) {
    if (info.entryPoint && /(?:^|\/)src\/main\.js$/.test(info.entryPoint)) entry = path.basename(outfile);
  }
  if (!entry) throw new Error('build: esbuild metafile has no entry output');
  const css = fs.readFileSync(P('style.css')), ch = crypto.createHash('sha1').update(css).digest('hex').slice(0, 10);
  fs.writeFileSync(P(`dist/style.${ch}.css`), css);
  const assets = walk('assets').filter(f => /\.(glb|webp|ogg|mp3|m4a|json|hdr|wasm)$/.test(f));
  for (const a of assets) { fs.mkdirSync(path.dirname(P('dist/' + a)), { recursive: true }); fs.copyFileSync(P(a), P('dist/' + a)); }
  const jsChunks = fs.readdirSync(P('dist')).filter(f => f.endsWith('.js')).sort();
  let html = fs.readFileSync(P('index.html'), 'utf8').replace(/(src=["'])\.?\/?dist\/game\.js/, `$1${entry}`).replace(/(href=["'])\.?\/?style\.css/, `$1style.${ch}.css`);
  if (!/serviceWorker/.test(html)) html = html.replace('</body>', `<script>if('serviceWorker' in navigator&&!/[?&]nosw/.test(location.search))navigator.serviceWorker.register('./sw.js',{scope:'./'});</script></body>`);
  fs.writeFileSync(P('dist/index.html'), html);
  // Big lazy chunks (Rapier physics, ~4 MB) are NOT precached at install; the game prefetches them after the first frame
  // and the fetch handler caches them at runtime. They still feed the version hash.
  const lazy = jsChunks.filter(f => f !== entry && fs.statSync(P('dist/' + f)).size > 1e6);
  // High-only texture maps (normal/ARM) are not precached so Low never downloads them; High fetches and the
  // fetch handler caches them at runtime. They still feed the version hash.
  const hiOnly = assets.filter(f => /textures\/.*_(nor|arm)\.webp$/.test(f)); lazy.push(...hiOnly);
  const pre = ['./', 'index.html', ...jsChunks.filter(f => !lazy.includes(f)), `style.${ch}.css`, ...assets.filter(f => !hiOnly.includes(f))];
  const vh = crypto.createHash('sha1'); [...pre.slice(1), ...lazy].forEach(f => vh.update(fs.readFileSync(P('dist/' + f)))); const V = 'ss-' + vh.digest('hex').slice(0, 10);
  fs.writeFileSync(P('dist/sw.js'), `/* generated by tools/build.js */
const V='${V}',PRE=${JSON.stringify(pre)};
self.addEventListener('install',e=>e.waitUntil(caches.open(V).then(c=>c.addAll(PRE)).then(()=>self.skipWaiting())));
self.addEventListener('activate',e=>e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k.startsWith('ss-')&&k!==V).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',e=>{const u=new URL(e.request.url);if(e.request.method!=='GET'||u.origin!==location.origin||!u.pathname.startsWith(new URL(self.registration.scope).pathname))return;
 if(e.request.mode==='navigate'){e.respondWith(fetch(e.request).then(r=>{const c=r.clone();caches.open(V).then(k=>k.put('./',c));return r}).catch(()=>caches.match('./')));return}
 e.respondWith(caches.match(e.request,{ignoreSearch:true}).then(r=>r||fetch(e.request).then(n=>{if(n.ok){const c=n.clone();caches.open(V).then(k=>k.put(e.request,c))}return n})))});
`);
  fs.writeFileSync(cache, key);
  const gz = f => zlib.gzipSync(fs.readFileSync(P('dist/' + f))).length;
  const sizes = [];
  const walkFiles = (rel) => {
    for (const ent of fs.readdirSync(P(rel), { withFileTypes: true })) {
      const child = rel + '/' + ent.name;
      if (ent.isDirectory()) walkFiles(child);
      else sizes.push({ file: child.slice('dist/'.length), raw: fs.statSync(P(child)).size });
    }
  };
  walkFiles('dist');
  sizes.sort((a, b) => a.file.localeCompare(b.file));
  const entryRaw = fs.statSync(P('dist/' + entry)).size;
  const total = sizes.reduce((n, s) => n + s.raw, 0);
  console.log(sizes.map(s => s.raw + '\t' + s.file).join('\n'));
  console.log(JSON.stringify({ version: V, entry, js: { raw: entryRaw, gzip: gz(entry) }, chunks: jsChunks, assets: assets.length, total }));
})();
